"""国家互联网信息办公室（CAC）专用抓取器。

为什么这是本项目最关键的数据源
------------------------------
网信办是 AI 专项法规的主要发文机构，且金融机构的生成式 AI 备案也在此办理。

下列条目均已由本抓取器在 2026-10-05 实网验证可从「部门规章」栏目自动发现
（日期为列表页上标注的发布日期，非施行日期）：

- 《生成式人工智能服务管理暂行办法》（2023-07-13）
- 《互联网信息服务深度合成管理规定》（2022-12-11）
- 《人工智能拟人化互动服务管理暂行办法》（2026-04-10）
- 《人工智能气象应用服务办法》（2025-04-30）
- 《人脸识别技术应用安全管理办法》（2025-03-21）
- 《个人信息保护合规审计管理办法》（2025-02-14）

因此该源与金融 AI 合规高度耦合——金融机构要用生成式 AI，必然同时受
网信办的备案要求与金融监管总局的业务合规要求双重约束。

特殊之处一：页面结构在 2026-10 前后改版，旧 URL 与旧选择器全部失效
----------------------------------------------------------------
早期（2026-10-03）本项目把该源记为「网络不可达（http=000，超时）」，并据此禁用。
2026-10-05 复核推翻了这一结论——**问题不在网络，而在 URL**：

- 旧地址 ``/zcfg/A093601index_1.htm`` 返回 **HTTP 404**（耗时 0.31s，不是超时）
- 站点首页 ``https://www.cac.gov.cn/`` 返回 **HTTP 200**（耗时 0.29s），站点完全可达
- 真实地址带 ``/wxzw/`` 前缀（网信政务 → 政策法规），栏目 ID 也已变更

这个误判的代价不小：该源是项目最高价值的数据源，被禁用后核心法规只能靠人工录入。
教训是 **http=000 必须区分「域名不可达」「路径不存在」「被防护拦截」三种情况**，
否则会把「改个 URL」就能修的问题误判成无解的运维问题。

改版后的页面结构也随之变化，``selectors`` 必须相应调整：

- 条目容器：内容条目统一在 ``#loadingInfoPage`` 容器内，
  而页面其余 ``li`` 全是站点导航（该页 38 个 li 中 13 个是导航）
- 日期节点：日期在 ``<div class="times">`` 中，**页面上没有任何 ``span``**
- 分页：**该栏目没有分页**。页面的 ``pagestat()`` 函数只是访问统计上报
  （POST 到 ``/cms/pub/interact/stat/``），与翻页无关；
  实测 ``A09370303index_2.htm`` 返回 404，20 条即为历史全量。
  曾把 ``pagestat()`` 误认为分页逻辑，是个典型的「看似配了分页、实则请求不存在的页面」。

特殊之处二：选择器不能依赖日期元素的存在
----------------------------------------
曾用 ``item: "li:has(div.times)"`` 来一次排除全部导航，当时测试全绿。
但它有个隐蔽缺陷：**它要求条目必须含日期元素**。一旦某条政策的日期因页面微调
而解析不到，该条会被选择器**直接排除**，根本不进入后续清洗逻辑——
这比「被判为导航后剔除」更危险，因为 ``dropped_navigation`` 计数不会增加，
流水线仍报 ``ok``，损失完全静默。

改用 ``#loadingInfoPage li``（按容器结构定位，与日期能否解析无关）后，
日期解析失败的条目会保留下来，并在 stale 台账中暴露出来供人工核验。
对应的反向测试见 ``test_cac_fetcher_keeps_undated_items_that_are_not_navigation``。

本抓取器自身不硬编码任何选择器，全部由 YAML 配置驱动；
上面记录的结构特征是为了让贡献者在页面再次改版时知道该看哪里。
"""

# 导入 Any 类型标注
from typing import Any

# 从基类导入所需设施
from finreg_ai.fetchers.base import BaseFetcher, RawDoc
# 从通用抓取器导入通用实现
from finreg_ai.fetchers.html_list import HtmlListFetcher


class CacFetcher(BaseFetcher):
    """网信办抓取器，处理 1 基页面的分页语义。

    注意：当前启用的三个栏目（部门规章 / 规范性文件 / 政策文件）**都没有分页**，
    因此 ``pagination.enabled`` 均为 false，本类实际只走单页路径。
    下面保留分页处理是因为将来若启用网信办的其他栏目（如「法律」）仍会遇到，
    且站点若恢复翻页也需要它。
    """

    # 抓取器名称，用于工厂匹配
    name = "cac"

    def _page_url(self, page: int, pagination: dict[str, Any]) -> str:
        """构造第 page 页的 URL。

        与通用实现的关键差异：网信办的 ``index_1`` 是第一页，
        因此页码直接用 ``page`` 本身，而不像通用实现那样用 ``page - 1``。

        这个差异如果处理错，第一页的内容会永远抓不到，
        而抓取结果看起来完全正常——这是最难察觉的一类 bug。
        """
        # 取出 URL 模板
        pattern = pagination.get("url_pattern")
        # 未配置模板时退回列表页地址（此时只有一页）
        if not pattern:
            # 返回配置的列表页地址
            return self.source.list_url or ""
        # 用列表页地址的目录部分作为前缀
        base = (self.source.list_url or "").rsplit("/", 1)[0]
        # 页码直接从 1 开始，不做偏移
        concrete = pattern.replace("{page}", str(page))
        # 拼接完整地址
        return f"{base}/{concrete}"

    def parse(self, html: str) -> list[RawDoc]:
        """解析网信办列表页。

        除通用解析外，额外做一处针对性过滤：网信办列表页含大量
        「政策解读」「图解」等衍生内容。这些内容本身有价值，
        但不是政策原文，不应作为政策记录入库——
        它们的 URL 通常包含特定路径片段，据此识别过滤。
        """
        # 复用通用解析逻辑
        docs = HtmlListFetcher(self.source, session=self.session).parse(html)
        # 结果容器
        kept: list[RawDoc] = []
        # 逐条过滤
        for doc in docs:
            # 排除解读与图解密生内容：这类内容不是规范性文件本身，
            # 混入会导致「同一政策出现两条记录」，破坏数据完整性
            if any(marker in doc.url for marker in ("/zhuanti/", "jiedu", "tujie")):
                # 跳过该条
                continue
            # 保留
            kept.append(doc)
        # 返回过滤结果
        return kept
